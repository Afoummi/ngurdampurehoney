import { toast } from "sonner";
import { supabase } from "@/integrations/supabase/client";

export interface ShopifyProduct {
  node: {
    id: string;
    title: string;
    description: string;
    handle: string;
    priceRange: {
      minVariantPrice: {
        amount: string;
        currencyCode: string;
      };
    };
    images: {
      edges: Array<{
        node: {
          url: string;
          altText: string | null;
        };
      }>;
    };
    variants: {
      edges: Array<{
        node: {
          id: string;
          title: string;
          price: {
            amount: string;
            currencyCode: string;
          };
          availableForSale: boolean;
          selectedOptions: Array<{
            name: string;
            value: string;
          }>;
        };
      }>;
    };
    options: Array<{
      name: string;
      values: string[];
    }>;
  };
}

// Proxy all Shopify requests through edge function for security
export async function storefrontApiRequest(query: string, variables: Record<string, unknown> = {}) {
  const { data, error } = await supabase.functions.invoke('shopify-storefront', {
    body: { query, variables },
  });

  if (error) {
    console.error('Shopify API error:', error);
    toast.error("Failed to fetch products", {
      description: "Please try again later.",
    });
    return null;
  }

  if (data?.error) {
    if (data.error.includes('402') || data.error.includes('billing')) {
      toast.error("Shopify: Payment required", {
        description: "Shopify API access requires an active Shopify billing plan.",
      });
    }
    return null;
  }

  if (data?.errors) {
    throw new Error(`Error calling Shopify: ${data.errors.map((e: { message: string }) => e.message).join(', ')}`);
  }

  return data;
}

